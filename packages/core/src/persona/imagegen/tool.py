_LOG = get_logger("imagegen.tool")


# Default factory description fed to the model. Kept terse — the model's
# system prompt is the right place for additional usage guidance; the
# persona's ``visual_style`` is merged in BEFORE the backend call so the
# model does not need to be told to invoke a style explicitly.
# Spec 25 T11b (§2.9): affirmative-capability framing. Leads with "YOU CAN"
# so the model does not refuse an image request despite the tool being wired
# (the §2.9 failure: a fluent "I can't generate images" while generate_image
# was available). Hedge language removed.
_DEFAULT_DESCRIPTION = (
    "YOU CAN generate images. Use this tool for ANY image request — "
    "illustrations, diagrams, photos, visual aids, or 'just make an image'. "
    "Do not say you cannot generate images: call this tool. It takes a text "
    "description and returns a generated image stored in the persona's "
    "workspace. The persona's visual style (if configured) is applied "
    "automatically."
)


def make_generate_image_tool(
    *,
    backend: ImageBackend,
    audit_logger: ToolAuditLogger | None = None,
    persona_id: str | None = None,
    persona_visual_style: str | None = None,
    persister: WorkspacePersister | None = None,
    description: str = _DEFAULT_DESCRIPTION,
    charge_hook: ImageChargeHook | None = None,
) -> AsyncTool:
    """Build the ``generate_image`` :class:`AsyncTool`.

    Composes hard-line categorical filter, visual-style merge, options
    validation, backend dispatch, and audit emission into one tool the
    Toolbox can register. The model supplies only ``prompt`` / ``size``
    / ``count`` / ``quality`` — every other parameter (visual style,
    persona id, audit sink) is bound at factory time.

    Args:
        backend: The :class:`persona.imagegen.protocol.ImageBackend`
            implementation to dispatch to (OpenAI gpt-image-1 via
            :class:`persona.imagegen.openai_image.OpenAIImageBackend`,
            Flux 1.1 [pro] via
            :class:`persona.imagegen.fal_image.FalImageBackend`, or any
            future provider). Composition root selects per
            :func:`persona.imagegen.load_image_backend`.
        audit_logger: Optional :class:`ToolAuditLogger`. When provided,
            every dispatched call emits exactly one
            :class:`ToolAuditEvent` with ``action="execute"`` — even for
            the hard-line-rejected path (audit fires BEFORE the
            provider is consulted; the audit trail is the forensic
            record of what was *attempted*).
        persona_id: Persona identifier for audit records. ``None`` for
            CLI development; audit lines then route to
            ``_cli.tools.jsonl``.
        persona_visual_style: The persona's
            :attr:`persona.schema.persona.PersonaIdentity.visual_style`
            (T10) which is merged into the prompt at dispatch time per
            D-15-4. ``None`` / empty / whitespace-only yields the
            identity branch in :func:`merge_visual_style` (no merge).
        persister: Optional :class:`WorkspacePersister` (Spec 28). When
            provided, generated image bytes are persisted to the persona
            workspace and the resolved :class:`PersistedArtifact` entries
            land on :attr:`ToolResult.artifacts` (chat-path persistence —
            closes the Spec 25 §2.9 KNOWN-LIMITATION). When ``None`` the
            result is byte-identical to the pre-Spec-28 shape (empty
            ``artifacts``); the operator ``/v1/imagegen`` path is unaffected
            (it persists via the service directly). A persist failure is
            surfaced as a structured ``ToolResult(is_error=True)`` so the
            model can recover.
        description: Tool description fed to the model. The default
            covers the spec §5 wording; override to surface persona-
            specific guidance.
        charge_hook: Optional :class:`ImageChargeHook` (R9-308). When
            provided it is asked to authorize every call AFTER the options
            validate and BEFORE the provider is called; a refusal returns a
            structured error (``insufficient_credits`` / ``daily_spend_cap``)
            and the provider is never called. The charge it returns is
            settled with the provider's result after a success and released
            after a failure.
            ``None`` (the CLI, core tests) bills nothing, as before. Core
            only defines the seam; the api implements it over its ledger.

    Returns:
        An :class:`AsyncTool` named ``generate_image``. The persona's
        ``tools`` allow-list (Spec 03 D-03-7) gates whether a given
        persona can dispatch ``generate_image`` at all — the same way
        ``code_execution`` / ``file_write`` / MCP tools are gated.

    Notes:
        The returned tool follows the @tool / Toolbox contract unchanged:
        argument-validation errors and body-raised exceptions are
        converted to ``ToolResult(is_error=True, ...)`` by the ``@tool``
        decorator (D-03-5).
        :class:`persona.imagegen.errors.ImageGenError` subclasses (the
        domain-exception family) are caught here at the body and
        surfaced as structured failure results so the model can
        recover (e.g. provider rate limit → model explains "try again
        shortly"; content rejection → model offers an alternative).

        The backend NEVER touches disk inside this tool — the
        :class:`GenerationResult` carries raw bytes in
        :attr:`persona.imagegen.result.GeneratedImage.image_bytes`. The
        API service layer (Spec 15 T15) persists those bytes to the
        per-persona workspace and rewrites ``workspace_path`` on the
        outbound response. This factory's :class:`ToolResult` content
        is a short human-readable summary (image dimensions + count +
        media type); the structured ``data`` field carries the per-
        image metadata the service / model use downstream.
    """

    @tool(name="generate_image", description=description)
    async def generate_image(
        prompt: str,
        size: str = "1024x1024",
        count: int = 1,
        quality: str = "standard",
    ) -> ToolResult:
        # 1. Hard-line categorical filter — runs BEFORE the backend call.
        # On trigger: emit a content-hash-only audit (NEVER the prompt
        # itself) and return a structured failure ToolResult.
        triggered, category = is_hard_line_violation(prompt)
        if triggered:
            prompt_sha256 = hash_prompt_for_audit(prompt)
            _emit_hard_line_audit(
                audit_logger=audit_logger,
                persona_id=persona_id,
                provider=backend.provider_name,
                model=backend.model_name,
                category=category,
                prompt_sha256=prompt_sha256,
            )
            _LOG.warning(
                "generate_image hard-line trigger; provider not called",
                persona_id=persona_id or "<unknown>",
                category=category or "",
                prompt_sha256=prompt_sha256,
            )
            return ToolResult(
                tool_name="generate_image",
                content="content_rejected_hard_line",
                is_error=True,
                metadata={
                    "outcome": "content_rejected_hard_line",
                    "category": category or "",
                    "prompt_sha256": prompt_sha256,
                },
            )

        # 2. Merge visual_style — identity branch when style is None /
        #    empty / whitespace-only OR the user prompt already
        #    specifies a style (user wins per D-15-4).
        merged_prompt = merge_visual_style(prompt, persona_visual_style)

        # 3. Validate ImageGenOptions — closes the closed-preset surface
        #    + the D-15-3 count<=2 cap (MAX_IMAGES_PER_CALL, R9-308). Bad
        #    values from the model land as
        #    structured failure (the @tool decorator's validation
        #    envelope already covers schema-level errors; this catches
        #    e.g. unknown ``size`` strings that pass the str type check
        #    but fail the Literal validation).
        try:
            options = _validated_options(size=size, count=count, quality=quality)
        except Exception as exc:  # noqa: BLE001 — ValidationError + value coercion + Literal misses
            _emit_options_error_audit(
                audit_logger=audit_logger,
                persona_id=persona_id,
                provider=backend.provider_name,
                model=backend.model_name,
                detail=str(exc),
            )
            return ToolResult(
                tool_name="generate_image",
                content=f"invalid_options: {exc}",
                is_error=True,
                metadata={
                    "outcome": "error",
                    "reason": "invalid_options",
                    "provider": backend.provider_name,
                    "model": backend.model_name,
                },
            )

        # 3b. R9-308: ask the charge hook BEFORE the provider is called, so an
        #     image the person cannot pay for is never made.
        charge: ImageCharge | None = None
        if charge_hook is not None:
            try:
                charge = await charge_hook.authorize(
                    options, provider=backend.provider_name, model=backend.model_name
                )
            except ImageChargeRefusedError as exc:
                return _refused_result(
                    exc,
                    audit_logger=audit_logger,
                    persona_id=persona_id,
                    provider=backend.provider_name,
                    model=backend.model_name,
                )

        # 4. Backend dispatch — adapter-level error funnel surfaces SDK
        #    exceptions as ContentRejectedError (moderation) or
        #    ImageGenError-family (auth / rate / transient / etc.).
        try:
            result = await _generate(
                backend, merged_prompt, options=options, charge=charge, persona_id=persona_id
            )
        except ContentRejectedError as exc:
            stage = exc.context.get("stage", "")
            reason = exc.context.get("reason", "provider_moderation")
            _emit_provider_rejection_audit(
                audit_logger=audit_logger,
                persona_id=persona_id,
                provider=backend.provider_name,
                model=backend.model_name,
                stage=stage,
                reason=reason,
            )
            _LOG.info(
                "generate_image provider rejection",
                persona_id=persona_id or "<unknown>",
                provider=backend.provider_name,
                stage=stage,
                reason=reason,
            )
            return ToolResult(
                tool_name="generate_image",
                content=f"content_rejected_provider: {exc}",
                is_error=True,
                metadata={
                    "outcome": "content_rejected_provider",
                    "stage": stage,
                    "reason": reason,
                    "provider": backend.provider_name,
                    "model": backend.model_name,
                },
            )
        except ImageGenError as exc:
            error_type = type(exc).__name__
            reason = exc.context.get("reason", error_type)
            _emit_error_audit(
                audit_logger=audit_logger,
                persona_id=persona_id,
                provider=backend.provider_name,
                model=backend.model_name,
                error_type=error_type,
                reason=reason,
            )
            _LOG.warning(
                "generate_image backend failure",
                persona_id=persona_id or "<unknown>",
                provider=backend.provider_name,
                error_type=error_type,
                reason=reason,
            )
            return ToolResult(
                tool_name="generate_image",
                content=f"{error_type}: {exc}",
                is_error=True,
                metadata={
                    "outcome": "error",
                    "reason": reason,
                    "error_type": error_type,
                    "provider": backend.provider_name,
                    "model": backend.model_name,
                },
            )

        # 5. Success — emit one audit event with outcome=ok and return a
        #    structured ToolResult. ``data`` carries per-image metadata
        #    (workspace_path is None at this layer — T15 service rewrites
        #    after disk persistence); ``content`` is a short human-
        #    readable summary the model can echo.
        # R9-308: the provider returned images, so they are charged now, before
        # persistence, the same point the request path trues up at.
        if charge is not None:
            await _settle(charge, result, persona_id=persona_id)
        image_count = len(result.images)
        _emit_success_audit(
            audit_logger=audit_logger,
            persona_id=persona_id,
            provider=result.provider,
            model=result.model,
            image_count=image_count,
            latency_ms=result.latency_ms,
            size=options.size,
        )
        media_types = sorted({img.media_type for img in result.images})
        # The first image's dimensions are representative (the provider
        # returns one consistent size per request); we surface them for
        # the model to echo without verbatim-rendering each image's
        # dimensions in ``content``.
        first = result.images[0]
        content_summary = (
            f"generated {image_count} image"
            f"{'s' if image_count != 1 else ''} "
            f"({first.width}x{first.height}, {', '.join(media_types)})"
        )

        # 6. Spec 28 — persist bytes to the workspace when a persister is
        #    injected (chat-path persistence; closes Spec 25 §2.9). Each
        #    persisted image yields a PersistedArtifact for the inline file
        #    card; we also reconcile data["images"][].workspace_path so the
        #    structured data carries the resolved reference. None ⇒ unchanged
        #    pre-Spec-28 shape (empty artifacts, workspace_path stays as the
        #    backend left it). A persist failure surfaces structured so the
        #    model can recover (D-28-X-persisted-artifact-shape).
        artifacts: tuple[PersistedArtifact, ...] = ()
        resolved_paths: list[str | None] = [img.workspace_path for img in result.images]
        if persister is not None:
            try:
                persisted: list[PersistedArtifact] = []
                for idx, img in enumerate(result.images):
                    ext = img.media_type.split("/")[-1]
                    artifact = await persister.persist(
                        img.image_bytes,
                        mime_type=img.media_type,
                        suggested_filename=f"generated_image_{idx}.{ext}",
                    )
                    # Images render inline as a thumbnail above the card (the
                    # web layer applies the D-28-7 size threshold).
                    persisted.append(artifact.model_copy(update={"rendered_inline": True}))
                    resolved_paths[idx] = artifact.workspace_path
                artifacts = tuple(persisted)
            except Exception as exc:  # noqa: BLE001 — any persist failure → structured result
                _LOG.warning(
                    "generate_image persist failed",
                    persona_id=persona_id or "<unknown>",
                    error=str(exc),
                )
                return ToolResult(
                    tool_name="generate_image",
                    content=f"persist_failed: {exc}",
                    is_error=True,
                    metadata={
                        "outcome": "error",
                        "reason": "persist_failed",
                        "provider": result.provider,
                        "model": result.model,
                    },
                )

        return ToolResult(
            tool_name="generate_image",
            content=content_summary,
            is_error=False,
            metadata={
                "outcome": "ok",
                "provider": result.provider,
                "model": result.model,
                "latency_ms": f"{result.latency_ms:.1f}",
                "image_count": str(image_count),
                "size": options.size,
            },
            data={
                "provider": result.provider,
                "model": result.model,
                "latency_ms": result.latency_ms,
                "images": [
                    {
                        "workspace_path": resolved_paths[idx],
                        "media_type": img.media_type,
                        "width": img.width,
                        "height": img.height,
                        "revised_prompt": img.revised_prompt,
                    }
                    for idx, img in enumerate(result.images)
                ],
            },
            artifacts=artifacts,
        )

    return generate_image


def _validated_options(*, size: str, count: int, quality: str) -> ImageGenOptions:
    """The model's arguments as options, with the count capped at the route's cap.

    :class:`ImageGenOptions` admits up to four (the backends' contract); a chat call may
    ask for no more than :data:`MAX_IMAGES_PER_CALL`, the same as the HTTP route (R9-308).
    """
    if count > MAX_IMAGES_PER_CALL:
        msg = f"count must be at most {MAX_IMAGES_PER_CALL} (got {count})"
        raise ValueError(msg)
    return ImageGenOptions(
        size=size,  # type: ignore[arg-type]
        count=count,
        quality=quality,  # type: ignore[arg-type]
    )


async def _generate(
    backend: ImageBackend,
    prompt: str,
    *,
    options: ImageGenOptions,
    charge: ImageCharge | None,
    persona_id: str | None,
) -> GenerationResult:
    """Call the provider; when it raises, release the charge before the error goes on.

    Any exception releases, not only the image errors the tool turns into results: an
    unexpected one still made no image, and an authorization may be holding money.
    """
    try:
        return await backend.generate(prompt, options=options)
    except BaseException:
        if charge is not None:
            await _release(charge, persona_id=persona_id)
        raise


async def _release(charge: ImageCharge, *, persona_id: str | None) -> None:
    """Release a charge after a failed generation; a ledger failure is logged, not raised."""
    try:
        await charge.release()
    except ImageChargeLedgerError as exc:
        _LOG.warning(
            "generate_image charge failed to release (fail-soft)",
            persona_id=persona_id or "<unknown>",
            error=str(exc),
        )


async def _settle(charge: ImageCharge, result: GenerationResult, *, persona_id: str | None) -> None:
    """Settle the charge for ``result``; a ledger failure is logged and never raised.

    By now the provider has made the images and billed us for them. Failing the tool here
    would take away an image the person already has without making the charge any more
    likely to land, so a ledger failure (which the hook reports as
    :class:`ImageChargeLedgerError` after recording it) is logged loudly instead. Anything
    else is a bug in the hook and is left to surface.
    """
    try:
        await charge.settle(result)
    except ImageChargeLedgerError as exc:
        _LOG.warning(
            "generate_image charge failed to settle (fail-soft)",
            persona_id=persona_id or "<unknown>",
            provider=result.provider,
            model=result.model,
            image_count=len(result.images),
            error_type=type(exc).__name__,
            error=str(exc),
        )


def _refused_result(
    exc: ImageChargeRefusedError,
    *,
    audit_logger: ToolAuditLogger | None,
    persona_id: str | None,
    provider: str,
    model: str,
) -> ToolResult:
    """The structured error for an image the person cannot pay for; the provider was not called."""
    reason = exc.context.get("reason", "insufficient_credits")
    _emit_error_audit(
        audit_logger=audit_logger,
        persona_id=persona_id,
        provider=provider,
        model=model,
        error_type=type(exc).__name__,
        reason=reason,
    )
    _LOG.info(
        "generate_image refused by its charge hook; provider not called",
        persona_id=persona_id or "<unknown>",
        provider=provider,
        reason=reason,
    )
    return ToolResult(
        tool_name="generate_image",
        # The message alone: it is written for the person, the context is for logs.
        content=f"{reason}: {exc.message}",
        is_error=True,
        metadata={
            "outcome": "error",
            "reason": reason,
            "provider": provider,
            "model": model,
        },
    )


# ---------------------------------------------------------------------------
# Audit-event emitters.
#
# Each emitter is a thin helper around :class:`ToolAuditEvent` construction
# so the @tool body stays readable. The four outcome strings (``ok`` /
# ``content_rejected_provider`` / ``content_rejected_hard_line`` /
# ``error``) land in :attr:`ToolAuditEvent.metadata["outcome"]` cleanly
# without a struct change (D-15-X-audit-event-extension).
# ---------------------------------------------------------------------------


def _emit_hard_line_audit(
    *,
    audit_logger: ToolAuditLogger | None,
    persona_id: str | None,
    provider: str,
    model: str,
    category: str | None,
    prompt_sha256: str,
) -> None:
    """Emit one ``outcome=content_rejected_hard_line`` audit event.

    The triggering prompt is **never** persisted — only the sha256 hash
    via ``metadata["prompt_sha256"]`` (D-15-X-hard-line-filter). The
    ``resource`` field carries the same hash so an operator searching by
    hash can correlate the audit event to the trigger without revealing
    the content.
    """
    if audit_logger is None:
        return
    audit_logger.emit(
        ToolAuditEvent(
            timestamp=datetime.now(UTC),
            persona_id=persona_id,
            tool_name="generate_image",
            action="execute",
            resource=f"sha256:{prompt_sha256}",
            is_error=True,
            metadata={
                "outcome": "content_rejected_hard_line",
                "category": category or "",
                "prompt_sha256": prompt_sha256,
                "provider": provider,
                "model": model,
            },
        )
    )


def _emit_provider_rejection_audit(
    *,
    audit_logger: ToolAuditLogger | None,
    persona_id: str | None,
    provider: str,
    model: str,
    stage: str,
    reason: str,
) -> None:
    """Emit one ``outcome=content_rejected_provider`` audit event.

    Distinguished from the hard-line audit by the ``outcome`` value AND
    by carrying ``stage`` (``"input"`` / ``"output"``) so post-hoc
    analysis can separate prompt-rejection from generated-bytes-flagged
    rejections (D-15-X-flagged-image-policy).
    """
    if audit_logger is None:
        return
    audit_logger.emit(
        ToolAuditEvent(
            timestamp=datetime.now(UTC),
            persona_id=persona_id,
            tool_name="generate_image",
            action="execute",
            resource=provider,
            is_error=True,
            metadata={
                "outcome": "content_rejected_provider",
                "stage": stage,
                "reason": reason,
                "provider": provider,
                "model": model,
            },
        )
    )


def _emit_error_audit(
    *,
    audit_logger: ToolAuditLogger | None,
    persona_id: str | None,
    provider: str,
    model: str,
    error_type: str,
    reason: str,
) -> None:
    """Emit one ``outcome=error`` audit event for a backend-raised failure.

    Covers every non-moderation :class:`ImageGenError` subclass
    (:class:`ImageGenUnavailableError` for auth failures,
    :class:`ImageProviderError` for rate-limit / transient /
    unsupported_option / timeout). The ``error_type`` /  ``reason`` pair
    is the discriminator callers branch on; the API route layer maps
    these to HTTP status codes (503 for unavailable, 502 for transient).
    """
    if audit_logger is None:
        return
    audit_logger.emit(
        ToolAuditEvent(
            timestamp=datetime.now(UTC),
            persona_id=persona_id,
            tool_name="generate_image",
            action="execute",
            resource=provider,
            is_error=True,
            metadata={
                "outcome": "error",
                "error_type": error_type,
                "reason": reason,
                "provider": provider,
                "model": model,
            },
        )
    )


def _emit_options_error_audit(
    *,
    audit_logger: ToolAuditLogger | None,
    persona_id: str | None,
    provider: str,
    model: str,
    detail: str,
) -> None:
    """Emit one ``outcome=error reason=invalid_options`` audit event.

    Fires when :class:`ImageGenOptions` validation rejects the model-
    supplied ``size`` / ``count`` / ``quality``. The audit trail records
    the attempt + the validation detail so the operator can see if a
    given model is repeatedly tripping the cap.
    """
    if audit_logger is None:
        return
    audit_logger.emit(
        ToolAuditEvent(
            timestamp=datetime.now(UTC),
            persona_id=persona_id,
            tool_name="generate_image",
            action="execute",
            resource=provider,
            is_error=True,
            metadata={
                "outcome": "error",
                "reason": "invalid_options",
                "detail": detail,
                "provider": provider,
                "model": model,
            },
        )
    )


def _emit_success_audit(
    *,
    audit_logger: ToolAuditLogger | None,
    persona_id: str | None,
    provider: str,
    model: str,
    image_count: int,
    latency_ms: float,
    size: str,
) -> None:
    """Emit one ``outcome=ok`` audit event for a successful generation.

    The success audit complements the failure audits so an operator can
    answer "how many image-gen calls happened on this persona, and how
    many succeeded?" by counting ``outcome=ok`` events directly.
    """
    if audit_logger is None:
        return
    audit_logger.emit(
        ToolAuditEvent(
            timestamp=datetime.now(UTC),
            persona_id=persona_id,
            tool_name="generate_image",
            action="execute",
            resource=provider,
            is_error=False,
            metadata={
                "outcome": "ok",
                "provider": provider,
                "model": model,
                "image_count": str(image_count),
                "latency_ms": f"{latency_ms:.1f}",
                "size": size,
            },
        )
    )
